float Renderer::TextWidthPixels(const std::string& text, const float scale) {
  return static_cast<float>(text.size()) * 6.0F * scale;
}

void Renderer::DrawText2D(const float x, const float y, const float scale, const std::string& text, const glm::vec4& color) {
  std::vector<glm::vec3> triangles;
  triangles.reserve(text.size() * 5 * 7 * 6);

  float cx = x;
  for (const char rawCh : ToUpperAscii(text)) {
    const auto glyph = Glyph(rawCh);
    for (int row = 0; row < 7; ++row) {
      for (int col = 0; col < 5; ++col) {
        if (glyph[row][col] != '1') {
          continue;
        }

        const float px = cx + static_cast<float>(col) * scale;
        const float py = y - static_cast<float>(row) * scale;

        triangles.push_back({px, py - scale, 0.0F});
        triangles.push_back({px + scale, py - scale, 0.0F});
        triangles.push_back({px + scale, py, 0.0F});

        triangles.push_back({px, py - scale, 0.0F});
        triangles.push_back({px + scale, py, 0.0F});
        triangles.push_back({px, py, 0.0F});
      }
    }
    cx += 6.0F * scale;
  }

  if (triangles.empty()) {
    return;
  }

  const glm::mat4 ortho = glm::ortho(0.0F, static_cast<float>(width_), 0.0F, static_cast<float>(height_), -1.0F, 1.0F);

  const unsigned int solidProgram = solidShader_.program.Get();
  backend_->UseProgram(solidProgram);
  const int mvpLoc = backend_->GetUniformLocation(solidProgram, "uMvp");
  const int colorLoc = backend_->GetUniformLocation(solidProgram, "uColor");
  backend_->SetUniformMat4(mvpLoc, &ortho[0][0]);
  backend_->SetUniformVec4(colorLoc, color.r, color.g, color.b, color.a);

  backend_->BindVertexArray(textVao_.Get());
  backend_->BindArrayBuffer(textVbo_.Get());
  backend_->UploadArrayBufferData(triangles.size() * sizeof(glm::vec3), triangles.data(), true);
  backend_->DrawTriangles(static_cast<int>(triangles.size()));
  backend_->BindVertexArray(0);
}

std::string Renderer::ToUpperAscii(const std::string& s) {
  std::string out = s;
  std::transform(out.begin(), out.end(), out.begin(), [](unsigned char c) { return static_cast<char>(std::toupper(c)); });
  return out;
}

